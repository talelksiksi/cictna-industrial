/*
 * cictna_ua.c: implementation of the C boundary described in cictna_ua.h.
 *
 * Why a shim exists at all
 * ------------------------
 * open62541's public API is not directly callable from C# for three reasons:
 *  1. Much of it is `static inline` functions and macros (UA_NODEID_NUMERIC,
 *     UA_ServerConfig_setMinimal, UA_Client_readValueAttribute and many more).
 *     Inline functions have no exported symbol, so P/Invoke cannot reach them.
 *  2. Its structs (UA_ServerConfig, UA_ClientConfig, UA_Variant...) are large,
 *     change between releases and depend on build options. Mirroring them in C#
 *     would break silently on every version bump.
 *  3. We link open62541 statically and hide its symbols (see CMakeLists.txt), so
 *     the only entry points into the library are the functions in this file.
 * The shim therefore exposes a small, stable, plain-C surface. Anything that
 * touches open62541 structs happens here, in C, compiled against the exact
 * headers of the pinned version.
 *
 * Conventions
 * -----------
 *  - Failures are reported as OPC UA status codes (0 = Good), never by crashing
 *    or printing. The managed side turns them into results.
 *  - Strings returned as const char* point to static storage inside the library.
 *  - Phase 0 contains only identity/health functions and a self test. Client
 *    and server handles arrive in Phase 1, each wrapped by a SafeHandle in C#.
 */
#include "cictna_ua.h"

#include <open62541/client.h>
#include <open62541/client_config_default.h>
#include <open62541/client_highlevel_async.h>
#include <open62541/plugin/log_stdout.h>
#include <open62541/server.h>
#include <open62541/server_config_default.h>

#include <stdio.h>
#include <string.h>

/* ---- identity ------------------------------------------------------------ */

int32_t cictna_ua_abi_version(void) {
    return CICTNA_UA_ABI_VERSION;
}

const char *cictna_ua_stack_version(void) {
    /* Generated by open62541's CMake into open62541/config.h from the git tag. */
    return UA_OPEN62541_VERSION;
}

const char *cictna_ua_encryption_backend(void) {
    /* Decided at build time by -DUA_ENABLE_ENCRYPTION=... in native/build.*.
     * The managed smoke test and unit tests fail if this is not "mbedtls",
     * so a build without encryption can never be shipped by accident. */
#if defined(UA_ENABLE_ENCRYPTION_MBEDTLS)
    return "mbedtls";
#elif defined(UA_ENABLE_ENCRYPTION_OPENSSL)
    return "openssl";
#else
    return "none";
#endif
}

uint32_t cictna_ua_features(void) {
    /* Reports the compile-time options the managed layer relies on. Checked at
     * startup so a library built with the wrong flags fails early and loudly. */
    uint32_t f = 0;
#ifdef UA_ENABLE_ENCRYPTION
    f |= CICTNA_UA_FEATURE_ENCRYPTION;
#endif
#if UA_MULTITHREADING >= 100
    /* >= 100 means open62541 takes an internal lock around every public API
     * call. Our C# layer still serializes calls per client (see docs/native-layer.md), but
     * the lock protects us if a callback and a managed call ever overlap. */
    f |= CICTNA_UA_FEATURE_MULTITHREADING;
#endif
#ifdef UA_ENABLE_SUBSCRIPTIONS
    f |= CICTNA_UA_FEATURE_SUBSCRIPTIONS;
#endif
#ifdef UA_ENABLE_METHODCALLS
    f |= CICTNA_UA_FEATURE_METHODCALLS;
#endif
#ifdef UA_ENABLE_HISTORIZING
    f |= CICTNA_UA_FEATURE_HISTORIZING;
#endif
    return f;
}

const char *cictna_ua_status_name(uint32_t status) {
    /* Needs UA_ENABLE_STATUSCODE_DESCRIPTIONS (on by default). Unknown codes
     * come back as "Unknown StatusCode", never NULL. */
    return UA_StatusCode_name(status);
}

/* ---- loopback self test ---------------------------------------------------
 *
 * Purpose: prove on the target machine that the whole stack works end to end
 * (sockets, the event loop, the binary encoder/decoder, secure channel and
 * session handshake), without any external server. Used by the smoke tests and
 * later by the simulator's health endpoint.
 *
 * Design: server and client run on the CALLING thread. open62541 is built
 * around event loops that the application drives (UA_Server_run_iterate,
 * UA_Client_run_iterate). Interleaving both loops on one thread avoids creating
 * threads in C, which would need different code on Windows and Linux. The
 * client therefore uses the asynchronous API: a synchronous call would block
 * while the server, on the same thread, could not answer.
 */

typedef struct {
    int done;             /* set by the callback when the read has finished */
    UA_StatusCode status; /* result of the read */
    int64_t time;         /* Server_ServerStatus_CurrentTime, 100 ns ticks since 1601 */
} ReadResult;

static void on_read(UA_Client *client, void *userdata, UA_UInt32 requestId,
                    UA_StatusCode status, UA_DataValue *value) {
    (void)client;
    (void)requestId;
    ReadResult *r = (ReadResult *)userdata;
    r->done = 1;
    r->status = status;
    if(status != UA_STATUSCODE_GOOD)
        return;
    /* A Good service result can still carry a value of the wrong type or no
     * value at all. Check instead of trusting the server. */
    if(!value || !value->hasValue ||
       !UA_Variant_hasScalarType(&value->value, &UA_TYPES[UA_TYPES_DATETIME])) {
        r->status = UA_STATUSCODE_BADTYPEMISMATCH;
        return;
    }
    r->time = *(UA_DateTime *)value->value.data;
}

uint32_t cictna_ua_selftest_loopback(uint16_t port, uint32_t timeout_ms, int64_t *out_time) {
    UA_StatusCode rc = UA_STATUSCODE_GOOD;
    UA_Server *server = NULL;
    UA_Client *client = NULL;
    int server_started = 0;

    if(out_time)
        *out_time = 0;

    /* Server: minimal config (SecurityPolicy None, anonymous login) on the
     * given port. Only errors are logged: the warnings this config produces
     * ("Unconfigured AccessControl", "no encrypting SecurityPolicy") are
     * expected for a self test and would only alarm whoever reads the log.
     * The config struct is moved into the server by UA_Server_newWithConfig. */
    UA_ServerConfig sc;
    memset(&sc, 0, sizeof(sc));
    sc.logging = UA_Log_Stdout_new(UA_LOGLEVEL_ERROR);
    rc = UA_ServerConfig_setMinimal(&sc, port, NULL);
    if(rc != UA_STATUSCODE_GOOD) {
        UA_ServerConfig_clear(&sc);
        return rc;
    }
    server = UA_Server_newWithConfig(&sc);
    if(!server)
        return UA_STATUSCODE_BADOUTOFMEMORY;

    /* Opens the listen socket. Fails here (for example BadCommunicationError)
     * when the port is taken; the unit tests cover that case. */
    rc = UA_Server_run_startup(server);
    if(rc != UA_STATUSCODE_GOOD)
        goto cleanup;
    server_started = 1;

    UA_ClientConfig cc;
    memset(&cc, 0, sizeof(cc));
    cc.logging = UA_Log_Stdout_new(UA_LOGLEVEL_ERROR);
    rc = UA_ClientConfig_setDefault(&cc);
    if(rc != UA_STATUSCODE_GOOD) {
        UA_ClientConfig_clear(&cc);
        goto cleanup;
    }
    cc.timeout = timeout_ms; /* per-request timeout inside open62541 */
    client = UA_Client_newWithConfig(&cc);
    if(!client) {
        rc = UA_STATUSCODE_BADOUTOFMEMORY;
        goto cleanup;
    }

    /* 127.0.0.1, not "localhost": avoids IPv6/IPv4 resolution differences
     * between machines (the server may not be able to listen on "::"). */
    char url[64];
    snprintf(url, sizeof(url), "opc.tcp://127.0.0.1:%u", (unsigned)port);
    rc = UA_Client_connectAsync(client, url);
    if(rc != UA_STATUSCODE_GOOD)
        goto cleanup;

    /* Drive both event loops until the session is active and the read has
     * completed, or the deadline passes. The monotonic clock is used so a
     * wall-clock change during the test cannot shorten or extend it. */
    UA_DateTime deadline = UA_DateTime_nowMonotonic() +
                           (UA_DateTime)timeout_ms * UA_DATETIME_MSEC;
    ReadResult rr = {0, UA_STATUSCODE_GOOD, 0};
    int read_sent = 0;
    while(!rr.done) {
        if(UA_DateTime_nowMonotonic() > deadline) {
            rc = UA_STATUSCODE_BADTIMEOUT;
            goto cleanup;
        }
        UA_Server_run_iterate(server, false); /* false: do not wait for events */
        UA_StatusCode it = UA_Client_run_iterate(client, 1); /* wait at most 1 ms */
        UA_SessionState session;
        UA_StatusCode connect_status;
        UA_Client_getState(client, NULL, &session, &connect_status);
        if(connect_status != UA_STATUSCODE_GOOD) {
            rc = connect_status;
            goto cleanup;
        }
        if(it != UA_STATUSCODE_GOOD) {
            rc = it;
            goto cleanup;
        }
        if(!read_sent && session == UA_SESSIONSTATE_ACTIVATED) {
            rc = UA_Client_readValueAttribute_async(
                client, UA_NODEID_NUMERIC(0, UA_NS0ID_SERVER_SERVERSTATUS_CURRENTTIME),
                on_read, &rr, NULL);
            if(rc != UA_STATUSCODE_GOOD)
                goto cleanup;
            read_sent = 1;
        }
    }
    rc = rr.status;
    if(rc == UA_STATUSCODE_GOOD && out_time)
        *out_time = rr.time;

cleanup:
    /* Every exit path, success or failure, comes through here so no socket,
     * session or allocation outlives the call. */
    if(client) {
        /* A clean disconnect sends CloseSession and CloseSecureChannel, which
         * the server must answer, so keep the server loop running while the
         * client closes. Bounded to about 200 iterations so a broken server
         * cannot hang the caller. */
        UA_Client_disconnectAsync(client);
        for(int i = 0; i < 200; i++) {
            UA_SecureChannelState channel;
            UA_Client_getState(client, &channel, NULL, NULL);
            if(channel == UA_SECURECHANNELSTATE_CLOSED)
                break;
            UA_Server_run_iterate(server, false);
            UA_Client_run_iterate(client, 1);
        }
        UA_Client_delete(client);
    }
    if(server) {
        if(server_started)
            UA_Server_run_shutdown(server);
        UA_Server_delete(server);
    }
    return rc;
}
