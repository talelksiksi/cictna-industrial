#!/usr/bin/env python3
"""Generate src/Cictna.Industrial.Core/StatusCodes.g.cs from the OPC UA StatusCode.csv.

The CSV comes from the OPC Foundation (MIT licence) and ships with open62541 in
tools/schema/StatusCode.csv, so the table always matches the pinned stack version.
Run after native/build.sh has fetched the sources, and whenever open62541 is bumped:

  python3 scripts/generate-status-codes.py
"""
import csv
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
CSV = ROOT / "native" / ".deps" / "open62541" / "tools" / "schema" / "StatusCode.csv"
OUT = ROOT / "src" / "Cictna.Industrial.Core" / "StatusCodes.g.cs"
VERSIONS = ROOT / "native" / "versions.env"


def cs_string(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main() -> int:
    if not CSV.exists():
        print(f"{CSV} not found, run native/build.sh first", file=sys.stderr)
        return 1
    tag = re.search(r"^OPEN62541_TAG=(.*)$", VERSIONS.read_text(), re.M).group(1).strip()
    rows = []
    with CSV.open(newline="", encoding="utf-8") as f:
        for name, code, desc in csv.reader(f):
            rows.append((name.strip(), int(code, 16), desc.strip()))

    lines = [
        "// <auto-generated>",
        f"// Generated by scripts/generate-status-codes.py from StatusCode.csv (OPC Foundation, MIT licence)",
        f"// as shipped with open62541 {tag} in tools/schema. Do not edit by hand.",
        "// </auto-generated>",
        "",
        "namespace Cictna.Industrial.Core;",
        "",
        "/// <summary>All status codes defined by the OPC UA specification (Part 4 and Part 6).</summary>",
        "public static partial class StatusCodes",
        "{",
    ]
    for name, code, desc in rows:
        lines.append(f"    /// <summary>{desc.replace('&', '&amp;').replace('<', '&lt;').replace('>', '&gt;')}</summary>")
        lines.append(f"    public static readonly StatusCode {name} = new(0x{code:08X}u);")
        lines.append("")
    lines.append("    private static readonly Dictionary<uint, (string Name, string Description)> s_known = new()")
    lines.append("    {")
    for name, code, desc in rows:
        lines.append(f"        [0x{code:08X}u] = ({cs_string(name)}, {cs_string(desc)}),")
    lines.append("    };")
    lines.append("}")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {len(rows)} status codes to {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
